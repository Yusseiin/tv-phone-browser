// Builds the two files TizenBrew loads from this repository:
//   dist/agent.js   - injected into every page (targets Chromium 47, Tizen 3)
//   dist/service.js - Node service with the phone UI inlined (targets Node 4.4)
import * as esbuild from 'esbuild';
import { transformSync } from '@babel/core';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const pkg = JSON.parse(read('package.json'));
const PORT = 8765;

const banner = `/* Phone Browser ${pkg.version} - generated by build.mjs, edit src/ instead. */\n`;

async function bundle(entry, platform, define) {
    const result = await esbuild.build({
        entryPoints: [path.join(root, entry)],
        bundle: true,
        write: false,
        format: 'iife',
        platform,
        target: 'es2015',
        define,
        legalComments: 'none',
        charset: 'utf8',
        logLevel: 'warning'
    });
    return result.outputFiles[0].text;
}

function downlevel(code, targets) {
    return transformSync(code, {
        babelrc: false,
        configFile: false,
        sourceType: 'script',
        compact: false,
        comments: false,
        presets: [['@babel/preset-env', { targets, modules: false }]]
    }).code;
}

function inlineRemote() {
    const css = read('src/remote/remote.css');
    const js = read('src/remote/remote.js');
    return read('src/remote/index.html')
        .replace('<link rel="stylesheet" href="remote.css">', () => `<style>\n${css}</style>`)
        .replace('<script src="remote.js"></script>', () => `<script>\n${js}</script>`);
}

const common = {
    __VERSION__: JSON.stringify(pkg.version),
    __PORT__: String(PORT)
};

const agent = banner + downlevel(await bundle('src/agent/agent.js', 'browser', common), { chrome: '47' });

const service = banner + downlevel(await bundle('src/service/index.js', 'node', {
    ...common,
    __AGENT_SOURCE__: JSON.stringify(agent),
    __REMOTE_HTML__: JSON.stringify(inlineRemote()),
    __ICON_SVG__: JSON.stringify(read('src/remote/icon.svg'))
}), { node: '4.4' });

// TizenBrew evaluates the service in a vm sandbox without `global`/`globalThis`.
for (const bad of ['globalThis', 'regeneratorRuntime']) {
    if (service.includes(bad)) throw new Error(`dist/service.js references ${bad}, which the TV runtime lacks`);
}

fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/agent.js'), agent);
fs.writeFileSync(path.join(root, 'dist/service.js'), service);
console.log(`Built dist/agent.js (${(agent.length / 1024).toFixed(1)} KB) and dist/service.js (${(service.length / 1024).toFixed(1)} KB)`);
